-- =====================================================================
-- Glassmorphism :: Modern UI (v2)
-- =====================================================================
-- A small design system that sits on top of the original Infinity look.
--
-- IDENTITY, in priority order. Keep this order when adding anything:
--   1. Glassmorphism  - translucent frosted panels, layered depth,
--                       hairline highlights, content visible through chrome
--   2. Modern UI       - design tokens, restrained motion, generous spacing
--   3. Phoenix flavour - accent hue, diagonal shear, level/grade tiers
--
-- Phoenix is the *inspiration*, not the target: this is a glassmorphism theme
-- for Project OutFox, not a Phoenix reskin. If a Phoenix cue ever fights the
-- frosted-glass look, the glass wins.
--
-- What lives here:
--   * colour tokens      (palette / accent ramps / glass tint)
--   * motion tokens      (single place to slow down or disable motion)
--   * elevation helpers  (glass cards, hairlines, soft glows, focus rings)
--   * geometry tokens    (the diagonal shear, corner radius)
--
-- Nothing else in the theme has to be touched to retune the look, every
-- switch lives in ModernUI.Config below.
--
-- Style:
--   "aurora"  - new procedural animated background (default, recommended)
--   "video"   - keep the pre-rendered _Background.mp4 background
--   "classic" - fall back to the original Infinity chrome and background
--
-- Palette: phoenix | infinity
-- Accent:  phoenix2 | phoenix | cyan | violet | magenta | lime | amber | ice
-- Motion:  full | reduced | off        (reduced/off help low-end hardware)
-- =====================================================================

ModernUI = {}

ModernUI.Config = {
    Style      = "aurora",
    Palette    = "phoenix",
    Accent     = "phoenix2",
    Motion     = "full",
    Glass      = true,
    Grain      = true,
    Vignette   = true,
    Scanlines  = false,
    GlowBlobs  = 5,
    -- Horizontal shear on chrome: a Phoenix garnish, deliberately subtle so
    -- the frosted glass stays the headline effect. 0 = upright panels.
    Skew       = 0.03,
    -- Corner radius in pixels. Only has an effect when Graphics/Glass is
    -- installed; without that art, quads cannot be rounded at all.
    Radius     = 14,
    -- The diagonal specular streak across glass panels. Purely cosmetic.
    Sheen      = true,
}

-- ---------------------------------------------------------------------
-- Optional art detection
-- ---------------------------------------------------------------------
-- Graphics/Glass is generated by Other/gen_glass_assets.py and is optional.
-- When it is missing, every panel falls back to square-cornered quads, so the
-- theme still runs on a fresh checkout with no assets built.

local function HasGraphic(name)
    local ok, path = pcall(function() return THEME:GetPathG("", name, true) end)
    return ok and path ~= nil and path ~= ""
end

ModernUI.HasGlassArt = HasGraphic("Glass/Corner")
ModernUI.HasShadowArt = HasGraphic("Glass/Shadow")
ModernUI.HasSheenArt = HasGraphic("Glass/Sheen")
ModernUI.HasRingArt = HasGraphic("Glass/Ring")

