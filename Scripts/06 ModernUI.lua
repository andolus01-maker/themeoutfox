-- Status colours are shared by every palette.
ModernUI.Tokens = {
    Good = color("#3BE6A8"),
    Warn = color("#FFC24A"),
    Bad  = color("#FF5470"),
}

-- Swap palettes at runtime. The token table is mutated in place on purpose:
-- other files may already be holding a reference to ModernUI.Tokens, and
-- replacing the table would leave them pointing at the old colours.
function ModernUI.ApplyPalette(name)
    local palette = Palettes[name or ModernUI.Config.Palette] or Palettes.phoenix
    for key, value in pairs(palette) do
        ModernUI.Tokens[key] = color(value)
    end
    return ModernUI.Tokens
end

ModernUI.ApplyPalette()

-- Alpha carried by a colour token, used so helpers can keep the alpha that
-- is baked into the token instead of silently replacing it with 1.
local function ColorAlpha(shade)
    if type(shade) == "table" and type(shade[4]) == "number" then
        return shade[4]
    end
    return 1
end

-- Rebuild a colour token at a given alpha. Gradient edges need this: hard
-- coding raw RGB numbers there would silently ignore the active palette.
local function Tint(shade, alpha)
    if type(shade) ~= "table" then return color("0,0,0," .. tostring(alpha)) end
    return color(string.format("%.4f,%.4f,%.4f,%.4f",
        shade[1] or 0, shade[2] or 0, shade[3] or 0, alpha))
end

ModernUI.Tint = Tint

-- Accent ramp, 1 = bright end, 2 = deep end
function ModernUI.Accent(index)
    local ramp = AccentRamps[ModernUI.Config.Accent] or AccentRamps.phoenix2
    return color(ramp[index or 1])
end

function ModernUI.IsModern()
    return ModernUI.Config.Style ~= "classic"
end

function ModernUI.UseAurora()
    return ModernUI.Config.Style == "aurora"
end

function ModernUI.UseGlass()
    return ModernUI.IsModern() and ModernUI.Config.Glass
end

-- ---------------------------------------------------------------------
-- Geometry
-- ---------------------------------------------------------------------

-- Shared horizontal shear. Classic mode always stays upright.
function ModernUI.Skew()
    if not ModernUI.IsModern() then return 0 end
    return tonumber(ModernUI.Config.Skew) or 0
end

-- Corner radius, clamped so it can never exceed half of the smaller side.
-- Returns 0 when the corner art is missing, which is what makes every caller
-- fall back to plain quads automatically.
function ModernUI.Radius(width, height, requested)
    if not (ModernUI.IsModern() and ModernUI.HasGlassArt) then return 0 end
    local r = tonumber(requested) or tonumber(ModernUI.Config.Radius) or 0
    return math.max(0, math.min(r, math.floor(math.min(width, height) * 0.5)))
end

-- ---------------------------------------------------------------------
-- Motion
-- ---------------------------------------------------------------------

function ModernUI.MotionScale()
    local m = ModernUI.Config.Motion
    if m == "off" then return 0 end
    if m == "reduced" then return 0.55 end
    return 1
end

-- Scale a duration with the current motion setting.
function ModernUI.T(seconds)
    local scale = ModernUI.MotionScale()
    if scale == 0 then return 0.001 end
    return seconds * scale
end

-- Signature easing of the modern layer: snappy in, soft landing.
function ModernUI.EaseIn(actor, seconds)
    local duration = ModernUI.T(seconds or 0.5)
    if duration <= 0.01 then return actor:linear(0.001) end
    return actor:easeoutexpo(duration)
end

function ModernUI.EaseOut(actor, seconds)
    local duration = ModernUI.T(seconds or 0.35)
    if duration <= 0.01 then return actor:linear(0.001) end
    return actor:easeinexpo(duration)
end

-- ---------------------------------------------------------------------
-- Chart level and grade tiers (Phoenix style)
-- ---------------------------------------------------------------------
-- NOTE: the evaluation screen deliberately does NOT use GradeTier. Its grades
-- are official PIU sprite art from Graphics/LetterGrades, chosen by
-- Modules/PIU/Score.GradingEval.lua. Replacing that with generated text would
-- lose the authentic art. Use GradeTier where a grade is rendered as *text*,
-- such as personal bests in the song wheel.

-- Upper bound of each tier -> colour. Tune the numbers here, nothing else.
local LevelTiers = {
    { 4,  "#3BE6A8" },
    { 9,  "#39B6FF" },
    { 14, "#FFD44A" },
    { 18, "#FF9A3C" },
    { 21, "#FF5470" },
    { 24, "#C86BFF" },
}

function ModernUI.LevelColor(level)
    level = tonumber(level) or 0
    for _, tier in ipairs(LevelTiers) do
        if level <= tier[1] then return color(tier[2]) end
    end
    -- Anything above the last tier is the "extreme" bracket.
    return color("#7A28FF")
end

-- The theme's own grade codes, as produced by Modules/PIU/Score.Grading.lua
-- and Score.GradingEval.lua: a "Pass"/"Fail" prefix followed by a code where
-- a leading digit is a repeat count and "P" means "plus". So 3PS is SSS+ and
-- 2A is AA. Mapping them here means grade colours can be driven by the grade
-- the theme actually computed, instead of re-deriving one from a percentage.
local GradeNames = {
    ["3PS"] = "SSS+", ["3S"] = "SSS",
    ["2PS"] = "SS+",  ["2S"] = "SS",
    ["PS"]  = "S+",   ["S"]  = "S",
    ["3PA"] = "AAA+", ["3A"] = "AAA",
    ["2PA"] = "AA+",  ["2A"] = "AA",
    ["PA"]  = "A+",   ["A"]  = "A",
    ["B"]   = "B",    ["C"]  = "C",
    ["D"]   = "D",    ["F"]  = "F",
}

-- Translate a theme grade code into its display name.
-- Returns the name plus whether the run was a fail, because in PIU a failed
-- run is a fail no matter how good the letter looks.
function ModernUI.GradeName(grade)
    grade = tostring(grade or "F")
    local failed = grade:sub(1, 4) == "Fail"
    local code = grade:gsub("^Pass", ""):gsub("^Fail", "")
    return GradeNames[code] or code, failed
end

-- Minimum percentage -> grade name, highest first.
-- These mirror the score cutoffs in Modules/PIU/Score.Grading.lua (which works
-- in points out of 1000000) divided by 10000. Keep the two in sync: if they
-- drift, the same play gets one grade on the score plate and a different one
-- anywhere GradeTier is used.
local GradeTiers = {
    { 99.5, "SSS+" }, { 99,   "SSS" },
    { 98.5, "SS+"  }, { 98,   "SS"  },
    { 97.5, "S+"   }, { 97,   "S"   },
    { 96,   "AAA+" }, { 95,   "AAA" },
    { 92.5, "AA+"  }, { 90,   "AA"  },
    { 82.5, "A+"   }, { 75,   "A"   },
    { 65,   "B"    }, { 55,   "C"   },
    { 45,   "D"    },
}

-- Accepts either a 0-1 ratio (what the engine usually hands out) or an
-- already-scaled 0-100 percentage.
-- Prefer GradeName() when the theme has already computed a grade: this is a
-- derivation, that is the real thing.
function ModernUI.GradeTier(percent)
    percent = tonumber(percent) or 0
    if percent > 0 and percent <= 1 then percent = percent * 100 end

    for _, tier in ipairs(GradeTiers) do
        if percent >= tier[1] then return tier[2] end
    end
    return "F"
end

-- Colour for a grade. Accepts either a theme grade code ("Pass3PS") or a
-- display name ("SSS+").
function ModernUI.GradeColor(grade)
    local name, failed = ModernUI.GradeName(grade)
    if failed then return ModernUI.Tokens.Bad end

    local head = name:sub(1, 1)
    if head == "S" then return ModernUI.Accent(1) end
    if head == "A" then return ModernUI.Tokens.Good end
    if name == "F" then return ModernUI.Tokens.Bad end
    return ModernUI.Tokens.Warn
end

-- ---------------------------------------------------------------------
-- Elevation helpers
