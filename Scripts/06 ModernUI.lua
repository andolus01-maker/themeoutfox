-- A 1px bright line used to separate surfaces, the cheapest way to make
-- flat panels read as layered glass.
function ModernUI.Hairline(params)
    params = params or {}
    local width = params.w or 200
    local thickness = params.thickness or 1
    local shade = params.color or ModernUI.Tokens.Hairline
    local skew = params.skew or 0
    -- diffusealpha() replaces the alpha carried by the colour token, so the
    -- token's own alpha is the default here. Callers that want a brighter
    -- line (the glass card highlight, for example) still pass params.alpha.
    local alpha = params.alpha or ColorAlpha(shade)

    return Def.Quad {
        InitCommand = function(self)
            self:xy(params.x or 0, params.y or 0)
                :zoomto(width, thickness)
                :halign(params.halign or 0.5):valign(params.valign or 0.5)
                :skewx(skew)
                :diffuse(shade):diffusealpha(alpha)
        end
    }
end

-- Additive radial glow built from the texture the theme already ships.
function ModernUI.SoftGlow(params)
    params = params or {}
    local shade = params.color or ModernUI.Accent(1)
    local baseZoom = params.zoom or 1

    return Def.Sprite {
        Texture = THEME:GetPathG("", "Background/circle"),
        InitCommand = function(self)
            self:xy(params.x or 0, params.y or 0)
                :zoom(baseZoom)
                :blend("BlendMode_Add")
                :diffuse(shade)
                :diffusealpha(params.alpha or 0.2)

            if params.pulse and ModernUI.MotionScale() > 0 then
                -- pulse() drives zoom directly, so the magnitude has to be
                -- expressed in absolute zoom. Feeding it a bare 1 -> 1.06
                -- would throw away baseZoom and snap the glow down to 1x.
                -- params.pulse may be `true` (default ratio) or a number
                -- describing how far the glow should breathe.
                local ratio = tonumber(params.pulse) or 1.06
                self:pulse()
                    :effectmagnitude(baseZoom, baseZoom * ratio, 1)
                    :effectperiod(ModernUI.T(params.period or 4))
                    :effectoffset(params.offset or 0)
            end
        end
    }
end

-- Thin rounded outline, for avatar frames and focus states.
-- Caveat: Ring.png is a square texture, so stretching it to a strongly
-- non-square size distorts the corner radius. Use it where w and h are close.
function ModernUI.FocusRing(params)
    params = params or {}
    if not ModernUI.HasRingArt then return Def.Actor {} end

    return Def.Sprite {
        Texture = THEME:GetPathG("", "Glass/Ring"),
        InitCommand = function(self)
            self:xy(params.x or 0, params.y or 0)
                :zoomto(params.w or 96, params.h or 96)
                :halign(params.halign or 0.5):valign(params.valign or 0.5)
                :diffuse(params.color or ModernUI.Accent(1))
                :diffusealpha(params.alpha or 0.9)
        end
    }
end

-- Frosted panel: shadow -> translucent gradient body -> top highlight ->
-- optional sheen -> accent bar. This is the core of the theme's identity, so
-- keep it reading as *glass*: the body must stay translucent and tinted from
-- the palette, never an opaque plate.
--
-- Geometry is a nine-slice when Graphics/Glass is installed: straight edges
-- are quads, and the four corners are one rounded-corner sprite drawn four
-- times at 0/90/180/270 degrees. Without that art the radius resolves to 0 and
-- the panel is a single quad, exactly as before.
--
-- The shear is applied to the card's own ActorFrame rather than to each piece.
-- Skewing the slices individually would shift them by different amounts and
-- tear the corners away from the edges.
function ModernUI.GlassCard(params)
    params = params or {}
    local width  = params.w or 320
    local height = params.h or 120
    local halign = params.halign or 0.5
    local valign = params.valign or 0.5
    local alpha  = params.alpha or 0.55
    local accent = params.accent or ModernUI.Accent(1)
    local accentBar = params.accentBar ~= false
    local skew = params.skew or ModernUI.Skew()
    local radius = ModernUI.Radius(width, height, params.radius)

    -- Panel bounds relative to the frame's origin.
    local left, top = -halign * width, -valign * height
    local right, bottom = left + width, top + height

    local topShade = Tint(ModernUI.Tokens.SurfaceHi, alpha)
    local bottomShade = Tint(ModernUI.Tokens.Base, math.min(alpha + 0.2, 1))

    local card = Def.ActorFrame {
        InitCommand = function(self)
            self:xy(params.x or 0, params.y or 0):skewx(skew)
        end
    }

    -- Ambient shadow. The pre-blurred sprite is much softer than a quad, but a
    -- quad is a fine stand-in when the art is absent.
    if ModernUI.HasShadowArt then
        card[#card + 1] = Def.Sprite {
            Texture = THEME:GetPathG("", "Glass/Shadow"),
            InitCommand = function(self)
                self:zoomto(width + 40, height + 40)
                    :halign(halign):valign(valign)
                    :diffuse(color("#000008")):diffusealpha(0.45 * alpha)
            end
        }
    else
        card[#card + 1] = Def.Quad {
            InitCommand = function(self)
                self:zoomto(width + 12, height + 12)
                    :halign(halign):valign(valign)
                    :diffuse(color("#000008")):diffusealpha(0.32 * alpha)
            end
        }
    end

    if radius > 0 then
        -- Middle band: full width, carries the vertical gradient.
        card[#card + 1] = Def.Quad {
            InitCommand = function(self)
                self:zoomto(width, height - radius * 2)
                    :halign(0.5):valign(0.5)
                    :x((left + right) * 0.5):y((top + bottom) * 0.5)
                    :diffuse(ModernUI.Tokens.Glass or ModernUI.Tokens.Surface)
                    :diffusetopedge(Tint(ModernUI.Tokens.SurfaceHi, alpha))
                    :diffusebottomedge(bottomShade)
            end
        }

        -- Top and bottom bands, inset by the radius so they stop where the
        -- corner sprites begin.
        for _, band in ipairs({
            { y = top, valign = 0, shade = topShade },
            { y = bottom, valign = 1, shade = bottomShade },
        }) do
            card[#card + 1] = Def.Quad {
                InitCommand = function(self)
                    self:zoomto(width - radius * 2, radius)
                        :halign(0.5):valign(band.valign)
                        :x((left + right) * 0.5):y(band.y)
                        :diffuse(band.shade)
                end
            }
        end

        -- Four corners from one texture. Rotation is clockwise, and the source
        -- tile is the top-left corner, so 0/90/180/270 walks around the panel.
        for _, spot in ipairs({
            { x = left + radius * 0.5,  y = top + radius * 0.5,    rot = 0,   shade = topShade },
            { x = right - radius * 0.5, y = top + radius * 0.5,    rot = 90,  shade = topShade },
            { x = right - radius * 0.5, y = bottom - radius * 0.5, rot = 180, shade = bottomShade },
            { x = left + radius * 0.5,  y = bottom - radius * 0.5, rot = 270, shade = bottomShade },
        }) do
            card[#card + 1] = Def.Sprite {
                Texture = THEME:GetPathG("", "Glass/Corner"),
                InitCommand = function(self)
                    self:xy(spot.x, spot.y)
                        :zoomto(radius, radius)
                        :rotationz(spot.rot)
                        :diffuse(spot.shade)
                end
            }
        end
    else
        -- No corner art: one quad, square corners, same gradient.
        card[#card + 1] = Def.Quad {
            InitCommand = function(self)
                self:zoomto(width, height)
                    :halign(halign):valign(valign)
                    :diffuse(ModernUI.Tokens.Glass or ModernUI.Tokens.Surface)
                    :diffusetopedge(Tint(ModernUI.Tokens.SurfaceHi, alpha))
                    :diffusebottomedge(bottomShade)
            end
        }
    end

    -- Diagonal specular streak. Additive and very faint, so the slight overhang
    -- past a rounded corner is not noticeable.
    if ModernUI.HasSheenArt and ModernUI.Config.Sheen and params.sheen ~= false then
        card[#card + 1] = Def.Sprite {
            Texture = THEME:GetPathG("", "Glass/Sheen"),
            InitCommand = function(self)
                self:zoomto(width, height)
                    :halign(halign):valign(valign)
                    :blend("BlendMode_Add")
                    :diffuse(ModernUI.Tokens.Text)
                    :diffusealpha(params.sheenAlpha or 0.10)
            end
        }
    end

    -- Top highlight hairline, inset so it does not poke out of the corners.
    card[#card + 1] = ModernUI.Hairline {
        w = width - radius * 2, thickness = 1,
        x = (left + right) * 0.5,
        y = top,
        alpha = 0.9,
    }

    -- Accent bar, the single strongest "this is new" signal
    if accentBar then
        card[#card + 1] = Def.Quad {
            InitCommand = function(self)
                self:zoomto(width - radius * 2, params.accentThickness or 3)
                    :halign(0.5):valign(0)
                    :x((left + right) * 0.5)
                    :y(top)
                    :diffuse(accent)
                    :diffuserightedge(ModernUI.Accent(2))
                    :blend("BlendMode_Add")
                    :diffusealpha(0.85)
            end
        }
    end

    return card
end

-- Convenience wrapper so BGAnimations can build a full-width chrome bar.
function ModernUI.ChromeBar(params)
    params = params or {}
    local height = params.h or 84
    local skew = params.skew or ModernUI.Skew()
    -- A sheared quad pulls its top and bottom edges sideways, which would
    -- expose a wedge of background at the screen edges. Grow the bar by the
    -- offset the shear introduces so it always bleeds off-screen.
    local bleed = math.abs(skew) * height * 2 + 8

    return ModernUI.GlassCard {
        x = params.x or SCREEN_CENTER_X,
        y = params.y or 0,
        w = params.w or (SCREEN_WIDTH + bleed),
        h = height,
        halign = 0.5,
        valign = params.valign or 0,
        alpha = params.alpha or 0.6,
        accentBar = params.accentBar ~= false,
        accentThickness = params.accentThickness or 2,
        skew = skew,
        -- A bar that bleeds off both screen edges must not round those edges.
        radius = params.radius or 0,
    }
end

